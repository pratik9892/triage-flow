"""Generate supabase/seed/seed.sql with demo customers, orders and past tickets.

All dates are relative to now() so the dashboard always shows recent data.
Run: python3 scripts/generate_seed.py
"""
import json
import random
from pathlib import Path

random.seed(42)
OUT = Path(__file__).resolve().parent.parent / "supabase" / "seed" / "seed.sql"

customers = [
    ("Aarav Mehta", "aarav.mehta@example.com", "Mumbai"),
    ("Priya Nair", "priya.nair@example.com", "Bengaluru"),
    ("Rohan Kulkarni", "rohan.kulkarni@example.com", "Pune"),
    ("Sneha Iyer", "sneha.iyer@example.com", "Chennai"),
    ("Kabir Singh", "kabir.singh@example.com", "Delhi"),
    ("Ananya Das", "ananya.das@example.com", "Kolkata"),
    ("Vikram Joshi", "vikram.joshi@example.com", "Thane"),
    ("Meera Patel", "meera.patel@example.com", "Ahmedabad"),
    ("Arjun Reddy", "arjun.reddy@example.com", "Hyderabad"),
    ("Isha Kapoor", "isha.kapoor@example.com", "Jaipur"),
]

catalog = {
    "Bloom Skincare": [("BLM-SER-01", "Vitamin C Serum 30ml", 799), ("BLM-SPF-02", "Sunscreen SPF 50", 549),
                       ("BLM-MOI-03", "Ceramide Moisturiser", 649)],
    "UrbanThread": [("UT-TEE-11", "Oversized Cotton Tee", 899), ("UT-JNS-12", "Straight Fit Jeans", 1899),
                    ("UT-HOD-13", "Fleece Hoodie", 1499)],
    "Brewcraft Coffee": [("BC-BEAN-21", "Single Origin Beans 250g", 650), ("BC-FRP-22", "French Press 600ml", 1250)],
}
couriers = ["Delhivery", "Blue Dart", "Ekart", "Shadowfax", "XpressBees"]

# (status, placed_hours_ago, expected_in_days, delivered_hours_ago)
order_plan = [
    ("shipped", 70, 2, None), ("out_for_delivery", 50, 0, None), ("delivered", 200, -5, 120),
    ("placed", 5, 5, None), ("packed", 20, 4, None), ("shipped", 96, -1, None),  # last one is delayed
    ("delivered", 400, -14, 300), ("rto_initiated", 240, -6, None), ("cancelled", 150, None, None),
    ("returned", 600, -20, 500), ("shipped", 40, 3, None), ("delivered", 90, -2, 30),
    ("placed", 2, 6, None), ("out_for_delivery", 60, 0, None), ("delivered", 160, -4, 80),
    ("shipped", 30, 3, None), ("packed", 10, 5, None), ("delivered", 300, -10, 220),
    ("shipped", 120, -2, None), ("delivered", 72, -1, 24),
]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


lines = ["-- Demo data for TriageFlow. Generated by scripts/generate_seed.py",
         "-- Safe to re-run: wipes tickets, orders and customers first.",
         "truncate tickets, orders, customers, workflow_errors restart identity cascade;", ""]

lines.append("insert into customers (name, email, phone, city) values")
lines.append(",\n".join(f"  ({q(n)}, {q(e)}, {q('+91 98' + str(random.randint(10000000, 99999999)))}, {q(c)})"
                        for n, e, c in customers) + ";")
lines.append("")

orders = []
for i, (status, placed_h, exp_days, deliv_h) in enumerate(order_plan):
    oid = f"ORD-{10231 + i}"
    cust = customers[i % len(customers)]
    brand = list(catalog)[i % 3]
    picks = random.sample(catalog[brand], k=random.randint(1, 2))
    items = [{"sku": s, "name": n, "qty": 1, "price": p} for s, n, p in picks]
    amount = sum(it["price"] for it in items)
    pay = "cod" if i % 3 == 0 else "prepaid"
    courier = random.choice(couriers) if status not in ("placed", "packed", "cancelled") else None
    awb = str(random.randint(10**10, 10**11 - 1)) if courier else None
    orders.append((oid, cust, status))
    lines.append(
        "insert into orders (id, customer_id, brand, items, amount, payment_method, status, courier, awb, "
        "placed_at, expected_delivery, delivered_at) select "
        f"{q(oid)}, id, {q(brand)}, {q(json.dumps(items))}::jsonb, {amount}, {q(pay)}, {q(status)}, "
        f"{q(courier) if courier else 'null'}, {q(awb) if awb else 'null'}, "
        f"now() - interval '{placed_h} hours', "
        f"{('(now() + interval ' + q(str(exp_days) + ' days') + ')::date') if exp_days is not None else 'null'}, "
        f"{('now() - interval ' + q(str(deliv_h) + ' hours')) if deliv_h else 'null'} "
        f"from customers where email = {q(cust[1])};")
lines.append("")

# Historical tickets so the dashboard has two weeks of shape.
templates = {
    "wismo": ["Where is my order {o}? It was supposed to arrive by now.", "Can you share tracking for {o}?",
              "Hi, any update on my order {o}?"],
    "cancel_request": ["Please cancel my order {o}, I ordered by mistake."],
    "return_exchange": ["I want to exchange the size for order {o}.", "How do I return an item from {o}?"],
    "refund_status": ["My refund for {o} hasn't come yet, it's been a week."],
    "damaged_or_wrong_item": ["I received a damaged product in {o}. The bottle was leaking.",
                              "Wrong item delivered in order {o}!"],
    "payment_issue": ["Money got deducted twice for {o}."],
    "product_query": ["Is the vitamin C serum okay for sensitive skin?", "Do you ship to Guwahati?"],
    "complaint": ["Third time asking about {o}. Worst service ever, nobody replies!!"],
}
weights = {"wismo": 38, "cancel_request": 7, "return_exchange": 12, "refund_status": 9, "damaged_or_wrong_item": 9,
           "payment_issue": 5, "product_query": 12, "complaint": 8}
# Mirrors n8n/src/03_routing.js: only routine WISMO is answered automatically.
human_intents = {"cancel_request", "damaged_or_wrong_item", "payment_issue", "complaint", "refund_status",
                 "return_exchange", "product_query"}

lines.append("insert into tickets (external_id, channel, customer_email, customer_name, message, received_at, "
             "intent, sentiment, urgency, confidence, extracted_order_id, ai_summary, order_id, status, priority, "
             "routing_reason, draft_reply, processed_at, processing_ms, model, resolved_at) values")
rows = []
for n in range(70):
    intent = random.choices(list(weights), weights=list(weights.values()))[0]
    oid, cust, _ = random.choice(orders)
    msg = random.choice(templates[intent]).format(o=oid)
    hours_ago = random.uniform(1, 13 * 24)
    sentiment = {"complaint": "angry", "damaged_or_wrong_item": "negative",
                 "payment_issue": "negative"}.get(intent, random.choice(["neutral", "neutral", "neutral", "negative"]))
    urgency = "high" if sentiment == "angry" else random.choice(["low", "medium", "medium"])
    conf = round(random.uniform(0.62, 0.98), 2)
    if intent in human_intents or sentiment == "angry" or conf < 0.7:
        status = "resolved" if hours_ago > 48 else "needs_human"
        reason = ("Low model confidence" if conf < 0.7 else
                  "Angry customer: route to a person" if sentiment == "angry" else
                  f"Intent '{intent}' needs a human decision")
        prio = 1 if sentiment == "angry" else 2
    else:
        status, reason, prio = "auto_resolved", f"Safe intent '{intent}' with order data: auto-replied", 4
    proc_s = random.randint(4, 14)
    resolved = f"now() - interval '{hours_ago - random.uniform(0.5, 20):.2f} hours'" if status == "resolved" else "null"
    has_oid = oid in msg
    rows.append(
        f"  ({q(f'seed-{n:03d}')}, {q(random.choice(['email', 'email', 'whatsapp', 'web_chat', 'instagram']))}, "
        f"{q(cust[1])}, {q(cust[0])}, {q(msg)}, now() - interval '{hours_ago:.2f} hours', "
        f"{q(intent)}, {q(sentiment)}, {q(urgency)}, {conf}, {q(oid) if has_oid else 'null'}, "
        f"{q('Customer asks: ' + msg[:60])}, {q(oid) if has_oid else 'null'}, {q(status)}, {prio}, {q(reason)}, "
        f"null, now() - interval '{hours_ago:.2f} hours' + interval '{proc_s} seconds', "
        f"{random.randint(1800, 5200)}, 'seed-data', {resolved})")
lines.append(",\n".join(rows) + ";")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(rows)} tickets, {len(orders)} orders)")
